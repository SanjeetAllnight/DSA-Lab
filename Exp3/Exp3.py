import matplotlib.pyplot as plt
import pandas as pd
import seaborn as sns
df = sns.load_dataset('tips')
print("="*60)
print("1. DATASET OVERVIEW")
print("="*60)
print(f"Shape of Dataset (Rows, Columns): {df.shape}")
print(f"\nColumn Names: {list(df.columns)}")
print("\nData Types & Non-Null Counts:")
print(df.info())
num_cols = df.select_dtypes(include=['float64', 'int64']).columns.tolist()
cat_cols = df.select_dtypes(include=['category', 'object']).columns.tolist()
print(f"\nNumerical Variables: {num_cols}")
print(f"Categorical Variables: {cat_cols}")
print(f"\nMissing Values:\n{df.isnull().sum()}")
print(f"\nDuplicate Records Count: {df.duplicated().sum()}")
print("\nDescriptive Statistics (Numerical):")
print(df.describe())
print("\nDescriptive Statistics (Categorical):")
print(df.describe(include=['category', 'object']))
fig, axes = plt.subplots(2, 4, figsize=(18, 9))
sns.histplot(df['total_bill'], bins=15, kde=False, color='skyblue', ax=axes[0, 0])
axes[0, 0].set_title('Histogram of Total Bill')
axes[0, 0].set_xlabel('Total Bill ($)')
axes[0, 0].set_ylabel('Frequency')
sns.kdeplot(df['total_bill'], color='darkblue', fill=True, ax=axes[0, 1])
axes[0, 1].set_title('KDE Plot of Total Bill')
axes[0, 1].set_xlabel('Total Bill ($)')
axes[0, 1].set_ylabel('Density')
sns.boxplot(y=df['total_bill'], color='lightgreen', ax=axes[0, 2])
axes[0, 2].set_title('Box Plot of Total Bill')
axes[0, 2].set_ylabel('Total Bill ($)')
sns.violinplot(y=df['total_bill'], color='mediumpurple', ax=axes[0, 3])
axes[0, 3].set_title('Violin Plot of Total Bill')
axes[0, 3].set_ylabel('Total Bill ($)')
sns.countplot(x='day', data=df, palette='Set2', ax=axes[1, 0])
axes[1, 0].set_title('Count Plot of Day')
axes[1, 0].set_xlabel('Day of the Week')
axes[1, 0].set_ylabel('Count')
sns.barplot(x='day', y='tip', data=df, palette='Pastel1', ci=None, ax=axes[1, 1])
axes[1, 1].set_title('Bar Plot (Mean Tip by Day)')
axes[1, 1].set_xlabel('Day of the Week')
axes[1, 1].set_ylabel('Mean Tip ($)')
day_counts = df['day'].value_counts()
axes[1, 2].pie(day_counts, labels=day_counts.index, autopct='%1.1f%%', colors=sns.color_palette('Set3'))
axes[1, 2].set_title('Pie Chart of Day Distribution')
axes[1, 3].axis('off')
plt.tight_layout()
plt.show()